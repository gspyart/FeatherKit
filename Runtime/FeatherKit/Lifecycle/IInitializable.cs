namespace FeatherKit.Lifecycle
{
    /// <summary>
    /// Жизненный цикл того, что лежит в контексте: начало.
    ///
    /// Init зовётся, когда в контексте зарегистрированы уже все — и обычные классы,
    /// и компоненты со сцены. Это снимает вопрос порядка: в конструкторе объект видит
    /// только то, что успели создать до него, а к моменту Init — контекст целиком.
    /// Без этого приходится тасовать строки регистрации местами, пока не сойдётся.
    ///
    /// На объекты вне контекста не действует — их никто не обходит. Сценовому объекту
    /// второй путь инициализации рядом с Awake и Start только мешает: бери сервис лениво,
    /// при первом обращении.
    /// </summary>
    public interface IInitializable
    {
        void Init();
    }
}

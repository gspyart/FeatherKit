namespace FeatherKit.Lifecycle
{
    /// <summary>
    /// Жизненный цикл того, что лежит в контексте: конец.
    ///
    /// Release зовётся при выгрузке контекста, в порядке, обратном регистрации: кто
    /// зарегистрировался позже, мог подписаться на того, кто раньше. Перечислять
    /// объекты руками не надо.
    ///
    /// Сюда идут отписки, остановка корутин, освобождение ресурсов.
    /// </summary>
    public interface IReleasable
    {
        void Release();
    }
}

namespace FeatherKit.Updatables
{
    /// <summary>
    /// Сервис, зарегистрированный в контексте и получающий кадровый апдейт автоматически —
    /// MonoBehaviour ради этого заводить не надо. Всё, что тикается не контекстом, а своим
    /// владельцем (кулдауны, сервисы, которые тикает их состояние игры), интерфейс не реализует:
    /// иначе апдейт пришёл бы дважды.
    /// </summary>
    public interface IUpdatable
    {
        void OnUpdate(float deltaTime);
    }
}

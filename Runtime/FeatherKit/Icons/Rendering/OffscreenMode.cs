namespace FeatherKit.Icons
{
    /// <summary>Что делать с иконкой, когда её точка ушла за край экрана.</summary>
    public enum OffscreenMode
    {
        /// <summary>Просто спрятать. Так поступают с подсказками: не видно цель — не о чем говорить.</summary>
        Hide,

        /// <summary>Не выпускать за поле: иконка доезжает до границы и скользит по ней. Граница —
        /// край свободного от интерфейса места (<see cref="IconEdgeBounds"/>), а не экрана.</summary>
        ClampToEdge,

        /// <summary>Только у края: за кадром прижата к границе, цель в кадре — гаснет.
        /// Так указатель на далёкий выход не висит над самими воротами.</summary>
        EdgeOnly
    }
}

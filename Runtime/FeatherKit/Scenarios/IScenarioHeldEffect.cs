namespace FeatherKit.Scenarios
{
    /// <summary>
    /// Долгий эффект, который держит граф: звук по кругу, затемнение, тряска, блокировка игрока.
    /// Граф отпускает его на Stop, обрыве куска запуска, уничтожении и сбросе — эффект уходит плавно, не обрывом.
    /// </summary>
    public interface IScenarioHeldEffect
    {
        /// <summary>Начать плавно уходить. Может прийти и второй раз — повтор ничего не делает.</summary>
        void Release();
    }
}

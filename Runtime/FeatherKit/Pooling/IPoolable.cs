namespace FeatherKit.Pooling
{
    /// <summary>
    /// Реализуй на компоненте, которому нужно сбрасывать/готовить своё состояние
    /// (HP, таймеры, подписки и т.п.) при выдаче из пула и при возврате в пул.
    /// Если интерфейс не реализован — пул просто включает/выключает GameObject.
    /// </summary>
    public interface IPoolable
    {
        /// <summary>
        /// Вызывается сразу после включения объекта и установки позиции/поворота.
        /// Пул передаёт себя, чтобы объект мог вернуться сам — иначе ссылку на пул
        /// пришлось бы протаскивать через всех, кто его спавнит.
        /// </summary>
        void OnSpawned(PoolManager owner);

        /// <summary>Вызывается перед выключением объекта при возврате в пул.</summary>
        void OnDespawned();
    }
}

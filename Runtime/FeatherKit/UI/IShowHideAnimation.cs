using System;
using UnityEngine;

namespace FeatherKit.UI
{
    /// <summary>
    /// Показать элемент интерфейса и убрать его за время анимации — и сказать, когда та доиграла.
    /// - интерфейсом: чем анимируют — твинами, клипами, кодом — дело самого элемента;
    /// - ради колбека и заведён: уходящий в пул объект нельзя убрать в тот же кадр.
    /// </summary>
    public interface IShowHideAnimation
    {
        /// <summary>Появиться. Колбек — когда появление доиграло.</summary>
        void Show(Action done = null);

        /// <summary>Уйти. Колбек — когда элемента на экране уже нет.</summary>
        void Hide(Action done = null);

        /// <summary>Уйти сразу, без анимации: так прячут то, что игрок и не видел открытым.</summary>
        void HideInstant();

        /// <summary>Показан ли элемент. Уезжающий уже не показан, хотя ещё на экране.</summary>
        bool IsShown { get; }

        /// <summary>Позицию ставит ведущий, как рендер — иконке над миром: анимация её не пишет,
        /// а отдаёт сдвиг через <see cref="PositionOffset"/>. Ставит ведущий, взяв элемент.</summary>
        bool PositionDriven { get; set; }

        /// <summary>
        /// Сдвиг, который анимация хочет добавить к позиции, пикселей раскладки. Ноль —
        /// элемент стоит на своём месте. Спрашивается каждый кадр тем, кто его ведёт.
        /// </summary>
        Vector2 PositionOffset { get; }
    }
}

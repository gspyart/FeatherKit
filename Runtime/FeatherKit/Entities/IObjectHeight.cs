using UnityEngine;

namespace FeatherKit.Entities
{
    /// <summary>
    /// «Какого я роста» — у объекта, НАД которым что-то показывают: полоска здоровья,
    /// цифра урона, значок. Смыслового центра для этого мало: он сидит на груди
    /// и у трёхметрового босса остаётся там же, где у обычного моба.
    ///
    /// Нужен потому, что показывает не игра, а кит: он про персонажей не знает и рост
    /// спрашивает вот так. Кто ростом не обладает — сундук, дверь — интерфейс не берёт,
    /// и спрашивающий обходится позицией объекта.
    ///
    /// Рост — свойство самого объекта, а куда его приложить, решает спрашивающий.
    /// </summary>
    public interface IObjectHeight
    {
        /// <summary>Рост, м: от подошв до макушки.</summary>
        float Height { get; }

        /// <summary>Макушка: точка над головой, в мире.</summary>
        Vector3 HeadPoint { get; }
    }
}

using System.Collections.Generic;

namespace FeatherKit.Modifiers
{
    /// <summary>
    /// Одна величина, собранная из вкладов разных хозяев: каждый под своим ключом
    /// и со своим сроком. Замах тяжёлого оружия тормозит, зелье ускоряет, лёд разгоняет —
    /// и всё это одновременно, не мешая друг другу.
    ///
    /// Ключи нужны потому, что одним числом это не выразить: тот, кто снимет свой вклад
    /// последним, вернул бы величину к базовой и затёр чужие. Ключ — сам просящий,
    /// поэтому свой вклад он обновляет и снимает, а чужие не трогает.
    ///
    /// Наследник задаёт ровно две вещи: базовое значение (когда вкладов нет) и правило
    /// смешивания. Отсюда и разные виды — произведение множителей, сумма прибавок,
    /// «хоть кто-то держит» у флагов.
    ///
    /// ПРАВИЛО СМЕШИВАНИЯ ОБЯЗАНО НЕ ЗАВИСЕТЬ ОТ ПОРЯДКА. Порядка у ключей нет и не будет:
    /// щит скилла и щит зелья приходят независимо, и кто раньше — неизвестно. Годятся
    /// произведение, сумма, минимум, максимум, «или»; «перебить своим значением» не годится
    /// — там результат зависел бы от того, кто успел первым. Деление отдельным видом
    /// не нужно: это множитель 1/x, а вычитание — отрицательная прибавка.
    ///
    /// Сроки считает сам, по чужому времени: иначе каждому, кто ставит вклад, пришлось бы
    /// держать свою корутину, а она не переживёт ни пул, ни смерть персонажа. Тикает
    /// хозяин стопки — тем же временем, в котором меряет свои сроки.
    ///
    /// Про то, ЧТО именно считается, не знает ничего — поэтому одна и та же стопка держит
    /// и скорость хода, и скорость разворота.
    /// </summary>
    public abstract class TimedModifiers<T>
    {
        // Один вклад: что даёт и сколько ему осталось жить. Ноль срока — держится, пока
        // не снимут руками.
        private struct TimedValue
        {
            public T Value;
            public float TimeLeft;
        }


        private readonly Dictionary<object, TimedValue> values = new Dictionary<object, TimedValue>();

        // Те же ключи списком. Нужен потому, что словарь нельзя перебирать и одновременно
        // править, а срок вклада правится на каждом тике. По списку идём индексом,
        // а словарь при этом просто адресуем по ключу.
        private readonly List<object> keys = new List<object>();

        private T current;

        // Итог не пересчитан. Начинаем с «не пересчитан», а не с базового значения:
        // базовое знает наследник, а спрашивать наследника из конструктора базы нельзя —
        // его поля в этот момент ещё не заведены.
        private bool isDirty = true;


        /// <summary>
        /// Итог: все действующие вклады, смешанные по правилу наследника. Вкладов нет —
        /// базовое значение.
        ///
        /// Считается после изменений, а не при каждом обращении: спрашивают его каждый
        /// кадр и не по разу, а меняется он в разы реже.
        /// </summary>
        public T Value
        {
            get
            {
                if (isDirty)
                {
                    current = Fold();
                    isDirty = false;
                }

                return current;
            }
        }

        /// <summary>
        /// Ни одного вклада не поставлено. Спрашивает тот, кто иначе тикал бы пустую
        /// стопку каждый кадр: вкладов чаще всего нет вовсе, а хозяев у стопки много.
        /// </summary>
        public bool IsEmpty => values.Count == 0;

        /// <summary>Значение, когда вкладов нет: единица у множителей, ноль у прибавок.</summary>
        protected abstract T Default { get; }


        // ── Вклады ────────────────────────────────────────────────────────

        /// <summary>
        /// Поставить свой вклад. Тот же ключ обновляет свой вклад, а не добавляет второй.
        ///
        /// Длительность — в том же времени, каким тикают; ноль означает «пока не снимут».
        /// </summary>
        public void Set(object key, T value, float duration = 0f)
        {
            if (key == null)
                return;

            if (!values.ContainsKey(key))
                keys.Add(key);

            values[key] = new TimedValue
            {
                Value = Sanitize(value),
                TimeLeft = duration
            };

            isDirty = true;
        }

        /// <summary>Снять свой вклад. Не ставил — ничего и не случится.</summary>
        public void Clear(object key)
        {
            if (key == null || !values.Remove(key))
                return;

            keys.Remove(key);

            isDirty = true;
        }

        /// <summary>Снять все. Нужно инстансу из пула: чужие вклады по наследству не передаются.</summary>
        public void ClearAll()
        {
            if (values.Count == 0)
                return;

            values.Clear();
            keys.Clear();

            isDirty = true;
        }

        /// <summary>
        /// Отсчитать сроки. Зовёт хозяин стопки — своим временем, тем же, в котором
        /// он задавал длительности.
        /// </summary>
        public void Tick(float deltaTime)
        {
            // Идём с конца: истёкший вклад снимается прямо на месте, и удаление не сдвигает
            // то, что ещё не смотрели.
            for (var i = keys.Count - 1; i >= 0; i--)
            {
                var key = keys[i];
                var value = values[key];

                // Ноль срока — вклад бессрочный, его снимут руками.
                if (value.TimeLeft <= 0f)
                    continue;

                value.TimeLeft -= deltaTime;

                if (value.TimeLeft > 0f)
                {
                    values[key] = value;
                    continue;
                }

                values.Remove(key);
                keys.RemoveAt(i);

                isDirty = true;
            }
        }


        // ── Правило наследника ────────────────────────────────────────────

        /// <summary>
        /// Смешать два значения. Порядок значения не имеет — см. описание класса.
        /// </summary>
        protected abstract T Combine(T accumulated, T value);

        /// <summary>
        /// Поправить пришедшее значение, если для этого вида есть заведомо негодные:
        /// отрицательный множитель развернул бы величину. По умолчанию берём как есть.
        /// </summary>
        protected virtual T Sanitize(T value) => value;

        private T Fold()
        {
            var result = Default;

            foreach (var pair in values)
                result = Combine(result, pair.Value.Value);

            return result;
        }
    }
}

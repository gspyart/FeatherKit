using System;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.Rendering.Universal;

namespace FeatherKit.Rendering
{
    /// <summary>
    /// Настройки тумана по высоте для одного Volume: где лежит его пол, насколько он закрывает
    /// даль, как быстро редеет вверх, каким цветом красит и как гуляют пятна. Отвечает ТОЛЬКО
    /// за числа — рисует их <see cref="HeightFogFeature"/>.
    ///
    /// Смысл в том, что это обычный VolumeComponent: локальный Volume с коллайдером
    /// и Blend Distance смешивает эти числа сам, средствами URP. Отсюда берутся участки
    /// карты со своим туманом — лощина, подвал, болото, — и отдельной сущности «зона тумана»
    /// заводить не нужно ни одной.
    ///
    /// ПЛАВНО НАРАСТАЕТ ТОЛЬКО ГУСТОТА. Всё, что задаёт ФОРМУ тумана — уровень пола, толщина
    /// слоя, дальность, размер пятен, ветер, — переключается разом, без смешивания. Иначе
    /// въезд в зону выглядел бы неопрятно: от высот и масштаба зависит, ГДЕ берутся выборки
    /// пятен, и пока эти числа ползут от зоны к зоне, весь рисунок тумана ползёт по экрану
    /// вместе с ними. Одна густота этим свойством не обладает — она множитель, и рисунка
    /// не сдвигает.
    ///
    /// Ловушка на изометрии: точку отсчёта локальных Volume URP берёт у камеры, а та висит
    /// метрах в двадцати от героя и входит в зоны не тогда. Лечится это на стороне камеры
    /// (volumeTrigger), а не здесь.
    /// </summary>
    [Serializable, VolumeComponentMenu("FeatherKit/Height Fog")]
    [SupportedOnRenderPipeline(typeof(UniversalRenderPipelineAsset))]
    [VolumeRequiresRendererFeatures(typeof(HeightFogFeature))]
    public sealed class HeightFogVolume : VolumeComponent, IPostProcessComponent
    {
        // ── Густота: то, что смешивается плавно ───────────────────────────────

        [Tooltip("Насколько туман закрывает пол, если смотреть на него сверху сквозь весь " +
                 "слой. 0.5 — пол виден наполовину, 0.9 — только силуэты. Ниже пола пелена " +
                 "гуще, выше — реже, по толщине слоя. Ноль — тумана нет вовсе, и проход " +
                 "не ставится. Это то самое число, которым туман и проявляется на въезде " +
                 "в зону")]
        // Долей закрытия, а не плотностью, намеренно — ради РОВНОГО ВХОДА В ЗОНУ. Volume
        // смешивает числа линейно, а видимая пелена растёт от плотности по экспоненте:
        // на пятой части пути к зоне плотный туман набегал бы уже больше чем наполовину.
        // Доля закрытия переводится в плотность логарифмом, и вход идёт ровно.
        //
        // Ноль по умолчанию — тоже намеренно. Стек Volume без единого переопределения отдаёт
        // ИМЕННО эти значения, поэтому любое другое число здесь означало бы туман во всех
        // сценах проекта разом, включая те, где про него не слышали.
        public ClampedFloatParameter coverage = new ClampedFloatParameter(0f, 0f, 0.99f);

        [Tooltip("Цвет тумана. Берётся как есть, без освещения: туман в стилизованной " +
                 "картинке должен читаться заданным оттенком, а не зависеть от того, куда " +
                 "повернулось солнце")]
        public ColorParameter color = new ColorParameter(new Color(0.72f, 0.76f, 0.82f), false, false, true);

        [Tooltip("Насколько пелена неровная. Ноль — ровная заливка, единица — густота " +
                 "гуляет от нуля до двойной. Середина читается как клубящаяся дымка. " +
                 "Рисунка пятен не сдвигает, поэтому смешивается плавно")]
        public ClampedFloatParameter noiseStrength = new ClampedFloatParameter(0.45f, 0f, 1f);

        [Tooltip("Насколько пятна меняют ЯРКОСТЬ тумана, а не только густоту. Густота " +
                 "в плотной пелене насыщается: где туман закрыл всё, пятна густоты не видны " +
                 "вовсе, а яркость видна и там. Плюс — густые пятна светлее, минус — темнее, " +
                 "единица — от нуля до двойной яркости. Тот же множитель, что и сила, " +
                 "поэтому тоже смешивается плавно")]
        public ClampedFloatParameter noiseBrightness = new ClampedFloatParameter(0f, -1f, 1f);


        // ── Форма: переключается разом ────────────────────────────────────────

        [Tooltip("Уровень пола тумана — координата Y в мире. Всё, что ниже, тонет в пелене " +
                 "целиком, всё что выше — редеет вместе с высотой")]
        public NoInterpFloatParameter floorHeight = new NoInterpFloatParameter(0f);

        [Tooltip("Толщина слоя в метрах: на этой высоте над полом туман редеет примерно " +
                 "втрое. Метрами, а не коэффициентом затухания, — высоту стен и обрывов " +
                 "видно в сцене линейкой, а коэффициент пришлось бы подбирать вслепую")]
        public NoInterpMinFloatParameter layerThickness = new NoInterpMinFloatParameter(5f, 0.1f);

        [Tooltip("Докуда туман густеет вдоль взгляда, метров: считаются последние метры " +
                 "луча ПЕРЕД поверхностью, а не первые от камеры, поэтому отъезд камеры " +
                 "на туман не влияет. Дальше этой черты пелена не набирается: так дальний " +
                 "план при взгляде вдоль земли не заливается в сплошную стену. Сверху луч " +
                 "короче этой черты, и работает она в основном на небо: ему отмеряется " +
                 "вся дальность")]
        public NoInterpMinFloatParameter maxDistance = new NoInterpMinFloatParameter(90f, 1f);

        [Tooltip("Размер пятна в метрах. Мелкие пятна на отлёте сливаются в шум и мельтешат, " +
                 "поэтому ставить меньше пары метров не стоит")]
        public NoInterpMinFloatParameter spotSize = new NoInterpMinFloatParameter(14f, 0.5f);

        [Tooltip("Куда и с какой скоростью плывут пятна, метров в секунду. Медленный дрейф " +
                 "оживляет сцену, быстрый читается как несущаяся позёмка")]
        public NoInterpVector3Parameter wind = new NoInterpVector3Parameter(new Vector3(0.5f, 0.05f, 0.3f));

        [Tooltip("Красить ли небо. Поверхности за горизонтом нет, и туману некуда " +
                 "набираться — поэтому небу отмеряется вся дальность разом. Снятая галка " +
                 "оставляет небо чистым: так видно, где кончается земля")]
        public BoolParameter fogSky = new BoolParameter(true);


        // ── IPostProcessComponent ─────────────────────────────────────────────

        // Нулевое закрытие значит «тумана тут нет»: фича по этому ответу не ставит проход
        // вовсе, и кадры вне туманных участков ничего не стоят.
        public bool IsActive()
        {
            return coverage.value > 0f;
        }
    }
}

using System;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.Rendering.Universal;

namespace FeatherKit.Rendering
{
    /// <summary>
    /// Настройки ОБЩЕГО тумана по высоте для одного Volume: где лежит его пол, насколько он
    /// закрывает даль, как быстро редеет вверх, каким цветом красит, как клубится и насколько
    /// его освещает сцена. Отвечает ТОЛЬКО за числа — рисует их <see cref="HeightFogFeature"/>.
    ///
    /// Областей тумана (<see cref="FogArea"/>) эти настройки не касаются: у каждой области
    /// свои. Общее у них только качество — в <see cref="HeightFogFeature"/>.
    ///
    /// Смысл в том, что это обычный VolumeComponent: локальный Volume с коллайдером
    /// и Blend Distance смешивает эти числа сам, средствами URP. Отсюда берутся участки
    /// карты со своим туманом — лощина, подвал, болото, — и отдельной сущности «зона тумана»
    /// заводить не нужно ни одной.
    ///
    /// ПЛАВНО НАРАСТАЕТ ТОЛЬКО ГУСТОТА. Всё, что задаёт ФОРМУ тумана — уровень пола, толщина
    /// слоя, дальность, размер пятен, ветер, — переключается разом, без смешивания. Иначе
    /// въезд в зону выглядел бы неопрятно: от высот и масштаба зависит, ГДЕ берутся выборки
    /// пятен, и пока эти числа ползут от зоны к зоне, весь рисунок тумана ползёт по экрану
    /// вместе с ними. Одна густота этим свойством не обладает — она множитель, и рисунка
    /// не сдвигает.
    ///
    /// Ловушка на изометрии: точку отсчёта локальных Volume URP берёт у камеры, а та висит
    /// метрах в двадцати от героя и входит в зоны не тогда. Лечится это на стороне камеры
    /// (volumeTrigger), а не здесь.
    /// </summary>
    [Serializable, VolumeComponentMenu("FeatherKit/Height Fog")]
    [SupportedOnRenderPipeline(typeof(UniversalRenderPipelineAsset))]
    [VolumeRequiresRendererFeatures(typeof(HeightFogFeature))]
    public sealed class HeightFogVolume : VolumeComponent, IPostProcessComponent
    {
        // ── Густота: то, что смешивается плавно ───────────────────────────────

        [Tooltip("Насколько туман закрывает пол, если смотреть на него сверху сквозь весь " +
                 "слой. 0.5 — пол виден наполовину, 0.9 — только силуэты. Ниже пола пелена " +
                 "той же густоты, выше — реже, по толщине слоя. Ноль — тумана нет вовсе, и проход " +
                 "не ставится. Это то самое число, которым туман и проявляется на въезде " +
                 "в зону")]
        // Долей закрытия, а не плотностью, намеренно — ради РОВНОГО ВХОДА В ЗОНУ. Volume
        // смешивает числа линейно, а видимая пелена растёт от плотности по экспоненте:
        // на пятой части пути к зоне плотный туман набегал бы уже больше чем наполовину.
        // Доля закрытия переводится в плотность логарифмом, и вход идёт ровно.
        //
        // Ноль по умолчанию — тоже намеренно. Стек Volume без единого переопределения отдаёт
        // ИМЕННО эти значения, поэтому любое другое число здесь означало бы туман во всех
        // сценах проекта разом, включая те, где про него не слышали.
        public ClampedFloatParameter coverage = new ClampedFloatParameter(0f, 0f, 0.99f);

        [Tooltip("Цвет тумана. При «свете сцены» на нуле виден как есть. При единице это цвет " +
                 "самих капель: на экране он умножается на свет вокруг, как цвет стены. " +
                 "Белый туман в тёмной сцене станет тёмным, а не будет светиться")]
        public ColorParameter color = new ColorParameter(new Color(0.72f, 0.76f, 0.82f), false, false, true);

        [Tooltip("Насколько туман закрывает то, что за ним. Единица — как настоящий туман. " +
                 "Ноль — туман ничего не закрывает и не темнит, только светится там, где на " +
                 "него падает свет. Вместе с нулевой подсветкой (Ambient Strength) это " +
                 "объёмные лучи от ламп и солнца без видимой пелены")]
        public ClampedFloatParameter opacity = new ClampedFloatParameter(1f, 0f, 1f);

        [Tooltip("Насколько туман клубится. Ноль — ровная заливка, единица — густота " +
                 "гуляет от нуля до двойной. Середина читается как клубящаяся дымка. " +
                 "Рисунка клубов не сдвигает, поэтому смешивается плавно")]
        public ClampedFloatParameter noiseStrength = new ClampedFloatParameter(0.45f, 0f, 1f);

        [Tooltip("Насколько клубы меняют ЯРКОСТЬ тумана, а не только густоту. Густота " +
                 "в плотной пелене насыщается: где туман закрыл всё, клубов густоты не видно " +
                 "вовсе, а яркость видна и там. Плюс — густые клубы светлее, минус — темнее, " +
                 "единица — от нуля до двойной яркости. Тот же множитель, что и сила, " +
                 "поэтому тоже смешивается плавно")]
        public ClampedFloatParameter noiseBrightness = new ClampedFloatParameter(0f, -1f, 1f);

        [Tooltip("Мелкие клубы поверх крупных: туман рваный, а не ватный. Ноль — их нет " +
                 "и они ничего не стоят, единица — густота заметно гуляет и в мелочах. " +
                 "Работают вместе с крупными: при нулевой силе клубов густоту не меняют. " +
                 "Стоят ещё одну выборку текстуры на каждом шаге")]
        public ClampedFloatParameter detailStrength = new ClampedFloatParameter(0f, 0f, 1f);


        // ── Освещение: тоже множители, смешиваются плавно ─────────────────────

        [Tooltip("Насколько туман освещается сценой. Ноль — светится своим цветом, как раньше. " +
                 "Единица — светлеет и темнеет вместе со сценой: от общей подсветки, солнца " +
                 "и ламп. Ноль ещё и бесплатен: свет вовсе не считается")]
        // Ноль по умолчанию — чтобы проекты, где туман уже подобран без света, не поменялись.
        public ClampedFloatParameter lightResponse = new ClampedFloatParameter(0f, 0f, 1f);

        [Tooltip("Насколько туман подсвечен общей подсветкой сцены. Единица — как стены. " +
                 "Ноль — туман тёмный и виден только там, где его освещают солнце и лампы: " +
                 "лучи и ореолы без пелены вокруг. Работает, только если «свет сцены» больше нуля")]
        public MinFloatParameter ambientStrength = new MinFloatParameter(1f, 0f);

        [Tooltip("Насколько туман ярче, если смотреть в сторону солнца или лампы. Ноль — " +
                 "одинаково со всех сторон. Чем больше, тем ярче ореол вокруг света " +
                 "и темнее туман, когда свет за спиной. Настоящая дымка — около 0.5–0.7")]
        public ClampedFloatParameter glowTowardLight = new ClampedFloatParameter(0.5f, 0f, 0.9f);

        [Tooltip("Насколько сильно лампы светят в тумане. Ноль — лампы туман не освещают " +
                 "и ничего не стоят. Единица — как в жизни, больше — ореолы ярче. " +
                 "Работает, только если «свет сцены» больше нуля. Отдельную лампу можно " +
                 "приглушить компонентом Fog Light Settings")]
        public MinFloatParameter lampStrength = new MinFloatParameter(1f, 0f);


        // ── Форма: переключается разом ────────────────────────────────────────

        [Tooltip("Уровень пола тумана — координата Y в мире. С галкой «следовать за камерой» — " +
                 "сколько метров от камеры: минус — ниже глаз. Ниже пола туман ровный, " +
                 "выше — редеет вместе с высотой. Двигает туман вверх и вниз, а густоты " +
                 "не меняет")]
        public NoInterpFloatParameter floorHeight = new NoInterpFloatParameter(0f);

        [Tooltip("Пол тумана ездит за камерой по высоте. Для игр, где герой поднимается " +
                 "и спускается: туман всегда на одной высоте от глаз, а не остаётся внизу. " +
                 "Клубы стоят в мире на месте — за камерой едет только сам слой")]
        public BoolParameter followCamera = new BoolParameter(false);

        [Tooltip("Насколько лениво туман догоняет камеру, секунд: за это время он проходит " +
                 "примерно две трети пути. Ноль — висит на камере жёстко и дёргается на " +
                 "каждом прыжке. Работает только с галкой «следовать за камерой»")]
        public NoInterpMinFloatParameter followDelay = new NoInterpMinFloatParameter(0.5f, 0f);

        [Tooltip("Толщина слоя в метрах: на этой высоте над полом туман редеет примерно " +
                 "втрое. Метрами, а не коэффициентом затухания, — высоту стен и обрывов " +
                 "видно в сцене линейкой, а коэффициент пришлось бы подбирать вслепую")]
        public NoInterpMinFloatParameter layerThickness = new NoInterpMinFloatParameter(5f, 0.1f);

        [Tooltip("Сколько метров тумана набирает взгляд, считая от места, где он вошёл " +
                 "в слой. Дальше пелена не густеет: дальний план при взгляде вдоль земли " +
                 "не заливается в сплошную стену. Отсчёт от входа в слой, а не от камеры, " +
                 "поэтому камера, поднятая над туманом, его не теряет")]
        public NoInterpMinFloatParameter maxDistance = new NoInterpMinFloatParameter(90f, 1f);

        [Tooltip("С какого расстояния от камеры начинается туман, метров. Ближе воздух " +
                 "чистый: пелена не висит перед лицом и не мылит то, что рядом. Резкой " +
                 "границы не будет — от этой черты туман набирается постепенно")]
        public NoInterpMinFloatParameter startDistance = new NoInterpMinFloatParameter(0f, 0f);

        [Tooltip("Размер клуба в метрах. Мелкие клубы на отлёте сливаются в шум и мельтешат, " +
                 "поэтому ставить меньше пары метров не стоит")]
        public NoInterpMinFloatParameter spotSize = new NoInterpMinFloatParameter(14f, 0.5f);

        [Tooltip("Размер мелкого клуба в метрах. Работает, только если сила мелких клубов " +
                 "больше нуля. Раза в три-пять меньше крупного — на глаз самое то")]
        public NoInterpMinFloatParameter detailSize = new NoInterpMinFloatParameter(3f, 0.25f);

        [Tooltip("Куда и с какой скоростью плывут клубы, метров в секунду. Медленный дрейф " +
                 "оживляет сцену, быстрый читается как несущаяся позёмка")]
        public NoInterpVector3Parameter wind = new NoInterpVector3Parameter(new Vector3(0.5f, 0.05f, 0.3f));

        [Tooltip("Красить ли небо. Поверхности за горизонтом нет, и туману некуда " +
                 "набираться — поэтому небу отмеряется вся дальность разом. Снятая галка " +
                 "оставляет небо чистым: так видно, где кончается земля")]
        public BoolParameter fogSky = new BoolParameter(true);


        // ── IPostProcessComponent ─────────────────────────────────────────────

        // Нулевое закрытие значит «общего тумана тут нет». Если и областей тумана в кадре
        // нет, фича не ставит проход вовсе, и такие кадры ничего не стоят.
        public bool IsActive()
        {
            return coverage.value > 0f;
        }
    }
}

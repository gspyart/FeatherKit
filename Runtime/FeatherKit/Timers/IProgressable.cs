namespace FeatherKit.Timers
{
    /// <summary>
    /// У этого есть измеримый ход: вскрытие сундука, постройка, каст, захват точки.
    /// Наружу отдаёт одно число — насколько дело продвинулось.
    ///
    /// Нужен затем, что показывают прогресс одни и те же полоски и заполнения, а считают
    /// его совсем разные системы. Полоске незачем знать, сундук перед ней или печь.
    /// </summary>
    public interface IProgressable
    {
        /// <summary>Насколько продвинулись: 0 — не начато, 1 — готово.</summary>
        float Progress { get; }
    }
}

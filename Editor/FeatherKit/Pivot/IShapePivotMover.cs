using UnityEngine;

namespace FeatherKit.EditorTools
{
    /// <summary>
    /// Перенос пивота у объектов, чья форма записана относительно пивота: коробки, точки сплайна (постройки Live Builder).
    /// Обычный перенос (<see cref="PivotMover"/>) у них сдвинул бы форму вместе с пивотом или отказал бы из-за своего меша;
    /// такой объект сам пересчитывает форму, чтобы в мире всё осталось на месте.
    /// Реализации находятся сами, по типу; нужен конструктор без параметров.
    /// </summary>
    public interface IShapePivotMover
    {
        // Объект — этого переноса: им займётся он, а не обычный перенос.
        bool IsOwnerOf(Transform root);

        // Пивот — в точку мира, форма и дети остаются на местах в мире. Шаг отмены уже открыт: правки записывать через Undo.
        void MovePivot(Transform root, Vector3 newPivot);
    }
}
